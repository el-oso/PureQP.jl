"""
    quadruped_contact() -> (P, q, A, l, u)

The problem as a caller states it, with the bound rows written out as the identity block `A`
begins with.
"""
function quadruped_contact()
    P = reshape(copy(QUAD_P_COLS), QUAD_N, QUAD_N)
    Agen = reshape(copy(QUAD_AGEN_COLS), QUAD_M - QUAD_N, QUAD_N)
    A = vcat(Matrix{Float64}(LinearAlgebra.I, QUAD_N, QUAD_N), Agen)
    return P, copy(QUAD_Q), A, copy(QUAD_L), copy(QUAD_U)
end

"""
    Xorshift(seed)

The xorshift64 generator of the reference implementation's own test, whose `()` draws
uniformly from `[-1, 1)`. Written out here rather than taken from `Random` so that an instance
of the family below is identified by its index alone.
"""
mutable struct Xorshift
    s::UInt64
end

function (r::Xorshift)()
    r.s ⊻= r.s << 13
    r.s ⊻= r.s >> 7
    r.s ⊻= r.s << 17
    return Float64(r.s >> 11) / Float64(UInt64(1) << 52) - 1.0
end

"""
    perturbations(reps; eps = 1e-13) -> Vector of (P, q, A)

`reps` instances of the family, the first unperturbed. Each entry of `P` (symmetrically), `q`
and the general rows of `A` is scaled by `1 + eps * ξ`. The bounds are left alone, so every
instance has the same solution to well under the solver's tolerance.

The draws run in one sequence, so instance `k` is reproducible only from the whole prefix
before it, which is why they are returned together rather than one at a time.
"""
function perturbations(reps::Integer; eps::Float64 = 1.0e-13)
    P0, q0, A0, _, _ = quadruped_contact()
    Agen0 = A0[(QUAD_N + 1):QUAD_M, :]
    rng = Xorshift(PERTURB_SEED)
    out = Vector{Tuple{Matrix{Float64}, Vector{Float64}, Matrix{Float64}}}(undef, reps)
    for k in 1:reps
        P, q, Agen = similar(P0), similar(q0), similar(Agen0)
        e = k == 1 ? 0.0 : eps
        # The lower triangle is drawn and mirrored, so the perturbed `P` stays symmetric.
        for i in 1:QUAD_N, j in 1:i
            P[i, j] = P[j, i] = P0[i, j] * (1 + e * rng())
        end
        for i in eachindex(q)
            q[i] = q0[i] * (1 + e * rng())
        end
        for i in axes(Agen, 1), j in axes(Agen, 2)
            Agen[i, j] = Agen0[i, j] * (1 + e * rng())
        end
        out[k] = (P, q, vcat(Matrix{Float64}(LinearAlgebra.I, QUAD_N, QUAD_N), Agen))
    end
    return out
end
